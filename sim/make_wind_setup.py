"""Build a gusty-wind world and a wind-enabled rc_cessna from YOUR PX4 Gazebo files, and link them into PX4.

Why this is needed: PX4's own windy.sdf sets a wind speed but loads no wind system, so the wind has no effect, and the
rc_cessna model does not accept wind. A world that lists any plugin no longer gets PX4's default plugin list
(server.config), so the generated world copies that whole list (IMU, GPS, airspeed, sensors, ...) and adds Gazebo's
WindEffects system with gusts (settings follow Gazebo's own example world gz-sim8/worlds/wind.sdf).

  python sim/make_wind_setup.py [--px4 ~/PX4-Autopilot] [--wind 4 0] [--scale 0.1] [--gust 0.25] [--name windy_gusts]

Writes sim/generated/worlds/<name>.sdf and sim/generated/models/rc_cessna_wind/, and puts symlinks to them into PX4's
worlds and models folders (nothing in PX4 is overwritten). Then:
  SIM_WORLD=windy_gusts scripts/sim.sh start gz_rc_cessna_wind

--scale is WindEffects' force_approximation_scaling_factor. Gazebo's wind force grows with the difference between wind
and link velocity, and this plane flies at about 14 m/s, so start small and check a normal flight first (calibration).
"""
import argparse, os, re, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def link(src, dst):
    if dst.is_symlink():
        if os.readlink(dst) == str(src):
            return "already linked"
        dst.unlink()
    elif dst.exists():
        sys.exit(f"{dst} exists and is not our link: not touching it")
    dst.symlink_to(src); return "linked"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--px4", default=os.path.expanduser("~/PX4-Autopilot"))
    ap.add_argument("--wind", type=float, nargs=2, default=[4.0, 0.0], metavar=("EAST", "NORTH"), help="mean wind in m/s")
    ap.add_argument("--scale", type=float, default=0.1, help="WindEffects force scaling (start small)")
    ap.add_argument("--gust", type=float, default=0.25, help="slow swing of wind speed, as a fraction (0.25 = +-25 percent)")
    ap.add_argument("--name", default="windy_gusts")
    a = ap.parse_args()
    gz = Path(a.px4) / "Tools" / "simulation" / "gz"
    cfg, world_in, model_in = gz / "server.config", gz / "worlds" / "default.sdf", gz / "models" / "rc_cessna" / "model.sdf"
    for p in (cfg, world_in, model_in):
        if not p.exists():
            sys.exit(f"missing {p}: is --px4 right?")

    # 1. PX4's default plugins, as world plugins (drop the server.config-only attributes)
    plugins = re.findall(r"<plugin\b.*?(?:/>|</plugin>)", re.sub(r"<!--.*?-->", "", cfg.read_text(encoding="utf-8-sig"), flags=re.S), flags=re.S)
    plugins = [re.sub(r'\s+entity_(?:name|type)="[^"]*"', "", p) for p in plugins]
    if not any("Imu" in p for p in plugins):
        sys.exit("server.config has no IMU plugin: unexpected format, stopping")
    wind_plugin = f"""<plugin filename="gz-sim-wind-effects-system" name="gz::sim::systems::WindEffects">
      <force_approximation_scaling_factor>{a.scale}</force_approximation_scaling_factor>
      <horizontal>
        <magnitude>
          <time_for_rise>10</time_for_rise>
          <sin><amplitude_percent>{a.gust}</amplitude_percent><period>15</period></sin>
          <noise type="gaussian"><mean>0</mean><stddev>0.05</stddev></noise>
        </magnitude>
        <direction>
          <time_for_rise>30</time_for_rise>
          <sin><amplitude>15</amplitude><period>20</period></sin>
          <noise type="gaussian"><mean>0</mean><stddev>0.05</stddev></noise>
        </direction>
      </horizontal>
      <vertical>
        <noise type="gaussian"><mean>0</mean><stddev>0.1</stddev></noise>
      </vertical>
    </plugin>"""
    w = world_in.read_text(encoding="utf-8-sig")   # PX4 files may start with a byte-order mark
    if "WindEffects" in w or "<wind>" in w:
        sys.exit("default.sdf already has wind settings: unexpected, stopping")
    w, n = re.subn(r"""<world\s+name=(['"])default\1\s*>""", f'<world name="{a.name}">\n    ' + "\n    ".join(plugins), w, count=1)
    if n != 1:
        sys.exit("could not find <world name='default'> in default.sdf")
    w = w.replace("</world>", f"    <wind><linear_velocity>{a.wind[0]} {a.wind[1]} 0</linear_velocity></wind>\n    {wind_plugin}\n  </world>", 1)
    out_w = REPO / "sim" / "generated" / "worlds"; out_w.mkdir(parents=True, exist_ok=True)
    note = "<!-- generated by px4-fault-detection-sim/sim/make_wind_setup.py from PX4 default.sdf and server.config -->"
    w = re.sub(r"^(\s*<\?xml[^>]*\?>)", r"\1\n" + note, w, count=1) if w.lstrip().startswith("<?xml") else note + "\n" + w
    (out_w / f"{a.name}.sdf").write_text(w)

    # 2. rc_cessna with wind enabled for all links (model-level enable_wind)
    m = model_in.read_text(encoding="utf-8-sig")
    m, n = re.subn(r"""<model\s+name=(['"])rc_cessna\1\s*>""", '<model name="rc_cessna_wind">\n    <enable_wind>true</enable_wind>', m, count=1)
    if n != 1:
        sys.exit("could not find <model name='rc_cessna'> in model.sdf")
    out_m = REPO / "sim" / "generated" / "models" / "rc_cessna_wind"; out_m.mkdir(parents=True, exist_ok=True)
    (out_m / "model.sdf").write_text(m)   # meshes still load from model://rc_cessna/...
    (out_m / "model.config").write_text('<?xml version="1.0"?>\n<model>\n  <name>rc_cessna_wind</name>\n  <version>1.0</version>\n'
                                        '  <sdf version="1.9">model.sdf</sdf>\n  <description>rc_cessna with enable_wind, generated by '
                                        'px4-fault-detection-sim/sim/make_wind_setup.py</description>\n</model>\n')
    print("world:", link(out_w / f"{a.name}.sdf", gz / "worlds" / f"{a.name}.sdf"), gz / "worlds" / f"{a.name}.sdf")
    print("model:", link(out_m, gz / "models" / "rc_cessna_wind"), gz / "models" / "rc_cessna_wind")
    print(f"wind {a.wind[0]} m/s east, {a.wind[1]} m/s north, speed swing +-{a.gust * 100:.0f} percent, direction +-15 degrees, "
          f"force scaling {a.scale}, plus {len(plugins)} PX4 default plugins")
    print(f"start it with:  SIM_WORLD={a.name} scripts/sim.sh start gz_rc_cessna_wind")


if __name__ == "__main__":
    main()
